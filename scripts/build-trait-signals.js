/**
 * Build the trait-name index used by the skills page and the PlayLog plugin.
 * A cell is included when its name, a skill it grants, or an effect it applies
 * is unique within that class. The plugin matches the character's trained
 * skills against this index.
 */
"use strict";

const fs = require("fs");
const path = require("path");
const https = require("https");

const ROOT = path.join(__dirname, "..");
const LORE = "C:/Users/me/OneDrive/Documents/The Lord of the Rings Online/LotRO Companion/app/data/lore";
const CDN = "https://lotroguides.atl1.cdn.digitaloceanspaces.com/data/builds/";
const CLASSES = [
  "beorning", "brawler", "burglar", "captain", "champion", "guardian",
  "hunter", "lore-master", "mariner", "minstrel", "rune-keeper", "warden",
];

function attrs(tag) {
  const out = {};
  const re = /(\w+)="([^"]*)"/g;
  let match;
  while ((match = re.exec(tag))) out[match[1]] = match[2];
  return out;
}

function norm(value) {
  return String(value || "").toLowerCase().replace(/\s+/g, " ").trim();
}

function get(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      if (res.statusCode !== 200) {
        res.resume();
        reject(new Error("HTTP " + res.statusCode + " for " + url));
        return;
      }
      const chunks = [];
      res.on("data", (chunk) => chunks.push(chunk));
      res.on("end", () => resolve(Buffer.concat(chunks).toString("utf8")));
    }).on("error", reject);
  });
}

function traitAliases(xml) {
  const aliases = {};
  const traitRe = /<trait\s+([^>]*?)(?:\/>|>([\s\S]*?)<\/trait>)/g;
  let match;
  while ((match = traitRe.exec(xml))) {
    const header = attrs(match[1]);
    if (!header.identifier) continue;
    const names = [];
    const body = match[2] || "";
    const childRe = /<(skill|effect)\s+([^/]*?)\/>/g;
    let child;
    while ((child = childRe.exec(body))) {
      const name = attrs(child[2]).name;
      if (name) names.push(name);
    }
    aliases[header.identifier] = names;
  }
  return aliases;
}

function addSignal(bucket, key, cell, maxRank) {
  if (!key) return;
  const current = bucket[key];
  const value = cell + ":" + maxRank;
  if (!current) {
    bucket[key] = value;
    return;
  }
  if (current === value) return;
  bucket[key] = null;
}

function classSignals(build, aliases) {
  const names = {};
  const icons = {};
  const trees = {};
  for (const tree of build.trees || []) {
    const treeName = norm(tree.name);
    if (treeName) trees[treeName] = tree.id;
    for (const trait of tree.traits || []) {
      if (!trait.id || trait.milestone) continue;
      const maxRank = trait.maxRank || 1;
      addSignal(names, norm(trait.name), trait.id, maxRank);
      for (const alias of aliases[trait.traitId] || []) {
        addSignal(names, norm(alias), trait.id, maxRank);
      }
      const icon = parseInt(trait.iconId, 10);
      if (icon) addSignal(icons, String(icon), trait.id, maxRank);
    }
  }
  const clean = (bucket) => {
    const out = {};
    for (const key of Object.keys(bucket)) {
      if (bucket[key]) out[key] = bucket[key];
    }
    return out;
  };
  return { names: clean(names), icons: clean(icons), trees };
}

function luaString(value) {
  return "\"" + String(value).replace(/\\/g, "\\\\").replace(/"/g, "\\\"") + "\"";
}

function luaClass(slug, signals) {
  const lines = ["\t[" + luaString(slug) + "] = {"];
  lines.push("\t\tnames = {");
  Object.keys(signals.names).sort().forEach((key) => {
    lines.push("\t\t\t[" + luaString(key) + "] = " + luaString(signals.names[key]) + ",");
  });
  lines.push("\t\t},");
  lines.push("\t\ticons = {");
  Object.keys(signals.icons).sort().forEach((key) => {
    lines.push("\t\t\t[" + key + "] = " + luaString(signals.icons[key]) + ",");
  });
  lines.push("\t\t},");
  lines.push("\t\ttrees = {");
  Object.keys(signals.trees).sort().forEach((key) => {
    lines.push("\t\t\t[" + luaString(key) + "] = " + luaString(signals.trees[key]) + ",");
  });
  lines.push("\t\t},");
  lines.push("\t},");
  return lines.join("\n");
}

function jsFile(classes) {
  return `/* Generated by scripts/build-trait-signals.js. Maps a trained skill or effect
   onto a trait cell. Names and icons are unique within each class. */
(function (root, factory) {
  var api = factory();
  if (typeof module === "object" && module.exports) module.exports = api;
  if (root) root.LOTRO_TRAIT_SIGNALS = api;
})(typeof window !== "undefined" ? window : globalThis, function () {
  var CLASSES = ${JSON.stringify(classes)};

  function norm(value) {
    return String(value || "").toLowerCase().replace(/\\s+/g, " ").trim();
  }

  function readSignal(text) {
    var parts = String(text || "").split(":");
    if (parts.length !== 2 || !/^[rby]-\\d-\\d$/.test(parts[0])) return null;
    var maxRank = parseInt(parts[1], 10);
    if (!maxRank || maxRank < 1) return null;
    return { cell: parts[0], maxRank: maxRank };
  }

  function rankFromText(value) {
    if (typeof value !== "string") return null;
    var match = value.match(/rank\\s*:?\\s*(\\d+)/i) || value.match(/(\\d+)\\s*\\/\\s*\\d+/);
    if (!match) return null;
    var rank = parseInt(match[1], 10);
    if (!rank || rank < 1 || rank > 99) return null;
    return rank;
  }

  function match(classKey, records) {
    var signals = CLASSES[classKey];
    var points = {};
    var unranked = 0;
    var spec = null;
    if (!signals) return { class: classKey, points: points, specialization: null, count: 0, unranked: 0 };
    (records || []).forEach(function (record) {
      if (!record) return;
      var name = norm(record.name);
      if (name && signals.trees[name]) spec = signals.trees[name];
      var signal = name && signals.names[name];
      if (!signal && record.iconImageId != null) signal = signals.icons[String(Math.floor(Number(record.iconImageId)))];
      signal = readSignal(signal);
      if (!signal) return;
      var rank = null;
      if (typeof record.rank === "number" && record.rank >= 1) rank = Math.floor(record.rank);
      if (rank == null) rank = rankFromText(record.description);
      var guessed = rank == null;
      if (guessed) rank = 1;
      if (rank > signal.maxRank) rank = signal.maxRank;
      if (rank < 1) return;
      if (!points[signal.cell] || rank > points[signal.cell]) {
        points[signal.cell] = rank;
        if (guessed && signal.maxRank > 1) unranked += 1;
      }
    });
    if (!spec) {
      var totals = { blue: 0, red: 0, yellow: 0 };
      Object.keys(points).forEach(function (cell) {
        var tree = cell.charAt(0) === "b" ? "blue" : cell.charAt(0) === "y" ? "yellow" : "red";
        totals[tree] += points[cell];
      });
      ["blue", "red", "yellow"].forEach(function (tree) {
        if (!spec || totals[tree] > totals[spec]) spec = tree;
      });
      if (!totals[spec]) spec = null;
    }
    return {
      class: classKey,
      points: points,
      specialization: spec,
      count: Object.keys(points).length,
      unranked: unranked
    };
  }

  return { match: match };
});
`;
}

async function main() {
  const aliases = traitAliases(fs.readFileSync(path.join(LORE, "traits.xml"), "utf8"));
  const classes = {};
  for (const slug of CLASSES) {
    const build = JSON.parse(await get(CDN + slug + ".json"));
    classes[slug] = classSignals(build, aliases);
    const nameCount = Object.keys(classes[slug].names).length;
    const iconCount = Object.keys(classes[slug].icons).length;
    console.log(slug + " names=" + nameCount + " icons=" + iconCount);
  }

  const jsPath = path.join(ROOT, "js", "trait-signals.js");
  fs.writeFileSync(jsPath, jsFile(classes));
  const luaPath = "C:/Users/me/OneDrive/Documents/The Lord of the Rings Online/Plugins/LotroGuides/PlayLog/TraitSignals.lua";
  const lua = [
    "-- Generated by scripts/build-trait-signals.js.",
    "-- name or icon -> \"tree-row-col:maxRank\". A name is included only when one cell uses it.",
    "TraitSignals = {",
    CLASSES.map((slug) => luaClass(slug, classes[slug])).join("\n"),
    "}",
    "",
  ].join("\n");
  fs.writeFileSync(luaPath, lua);
  console.log("wrote " + jsPath);
  console.log("wrote " + luaPath);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
